// Phase 7E release files: the precheck and postcheck end with the exact fingerprint SELECT, and
// each is one read-only DO block plus that SELECT (no psql meta-commands, no transaction control).
import assert from "node:assert/strict";
import test from "node:test";
import { readFileSync } from "node:fs";

const read = (name: string) =>
  readFileSync(new URL(`../supabase/release/phase7e/${name}`, import.meta.url), "utf8");
const fingerprint = read("fingerprint.sql");
const select = fingerprint.slice(fingerprint.indexOf("SELECT section, key, value FROM ("));

test("precheck and postcheck end with the exact fingerprint SELECT", () => {
  for (const name of ["precheck.sql", "postcheck.sql"]) {
    const text = read(name);
    assert.ok(text.endsWith(select), `${name} does not end with the fingerprint`);
    assert.doesNotMatch(text, /^\\/m, `${name} has a psql meta-command`);
    assert.doesNotMatch(
      text,
      /^\s*(BEGIN|COMMIT|ROLLBACK)\s*;/im,
      `${name} has transaction control`,
    );
    assert.equal((text.match(/^DO \$phase7e_(pre|post)check\$/gm) ?? []).length, 1);
    assert.match(
      text,
      /Generated by\s+(--\s+)?supabase\/tests\/support\/phase7e_release_generate\.mjs; do not/,
    );
  }
});

test("the precheck pins the 7D production baseline and the data 7E would treat differently", () => {
  const pre = read("precheck.sql");
  assert.match(
    pre,
    /Counts: functions 182,\s*\n?-- tables 54, indexes 203, policies 58, triggers 85/,
  );
  assert.match(pre, /posted credit memos, statements or other-currency documents exist/);
  assert.match(pre, /active budgets overlap/);
  assert.match(pre, /TimeZone must be UTC/);
  const post = read("postcheck.sql");
  assert.match(post, /Spent for budget % differs from the pre-7E figure/);
  assert.match(post, /removal record table must have no policies and no client grants/);
});

test("the README documents order, expected differences and read-only acceptance", () => {
  const readme = read("README.md");
  for (const phrase of [
    "182 → 208",
    "Run and enable RLS",
    "Expected differences",
    "Acceptance is read-only",
    "Spent $20,256.15",
    "migrate first, then deploy",
  ])
    assert.ok(readme.includes(phrase), phrase);
});
