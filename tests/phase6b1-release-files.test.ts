// Phase 6B.1 release files: the precheck and postcheck end with the exact fingerprint SELECT, and
// each is one read-only DO block plus that SELECT (no psql meta-commands, no transaction control).
import assert from "node:assert/strict";
import test from "node:test";
import { readFileSync } from "node:fs";

const read = (name: string) =>
  readFileSync(new URL(`../supabase/release/phase6b1/${name}`, import.meta.url), "utf8");
const fingerprint = read("fingerprint.sql");
const select = fingerprint.slice(fingerprint.indexOf("SELECT section, key, value FROM ("));

test("precheck and postcheck end with the exact fingerprint SELECT", () => {
  for (const name of ["precheck.sql", "postcheck.sql"]) {
    const text = read(name);
    assert.ok(text.endsWith(select), `${name} does not end with the fingerprint`);
    assert.doesNotMatch(text, /^\\/m, `${name} has a psql meta-command`);
    assert.doesNotMatch(
      text,
      /^\s*(BEGIN|COMMIT|ROLLBACK)\s*;/im,
      `${name} has transaction control`,
    );
    assert.equal((text.match(/^DO \$phase6b1_(pre|post)check\$/gm) ?? []).length, 1);
    assert.match(
      text,
      /Generated by\s+(--\s+)?supabase\/tests\/support\/phase6b1_release_generate\.mjs; do not/,
    );
    assert.doesNotMatch(text, /\b(INSERT|UPDATE|DELETE)\s+(INTO|FROM|public\.)/i, `${name} writes`);
  }
});

test("the precheck pins the 7E production baseline; the postcheck checks the old read shapes", () => {
  const pre = read("precheck.sql");
  assert.match(
    pre,
    /Counts: functions 208, tables 55, indexes 207,\s*\n?-- policies 58, triggers 89/,
  );
  assert.match(pre, /Phase 7E is not applied/);
  assert.match(pre, /TimeZone must be UTC/);
  assert.match(pre, /the Price Intelligence signatures differ/);
  const post = read("postcheck.sql");
  assert.match(post, /the deployed app''s Price Intelligence reads changed shape/);
  assert.match(post, /'unitSavings'/);
  assert.match(post, /set_config\('request\.jwt\.claim\.sub', '', true\)/);
  assert.match(post, /inventory_price_history_org_recent_idx/);
});

test("the fingerprint reports per-organization price state only after the migration", () => {
  assert.match(fingerprint, /'price', o\.id::text/);
  assert.match(
    fingerprint,
    /to_regprocedure\('public\.price_product_state\(uuid, uuid\[\], date, boolean\)'\) IS NULL THEN 'absent'/,
  );
  assert.match(fingerprint, /same_sku_increases=/);
});

test("the README documents order, expected differences, FC Cincinnati and the benchmark exception", () => {
  const readme = read("README.md");
  for (const phrase of [
    "208 → 227",
    "207 → 209",
    "Run and enable RLS",
    "Expected differences",
    "Acceptance is read-only",
    "products=74 | observations=81 | insufficient_identity=5",
    "migrate first, then deploy",
    "Benchmark exception",
  ])
    assert.ok(readme.includes(phrase), phrase);
});
